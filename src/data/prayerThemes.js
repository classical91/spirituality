export function getRandomPrayerTheme() {
  const all = prayerThemesCategories.flatMap((cat) =>
    cat.themes.map((theme) => ({
      title: theme.title,
      category: cat.label,
      prayers: prayerTextByTitle[theme.title] || [],
    }))
  );
  return all[Math.floor(Math.random() * all.length)];
}
