// Resolve both canonical paths and any legacy aliases to the owning portal.
export const portalsByPath = Object.fromEntries(
  portalCatalog
    .filter((p) => !p.routeHidden)
    .flatMap((p) => [
      [p.path, p],
      ...(p.aliases || []).map((alias) => [alias, p]),
    ])
);

export function searchPortals(query) {
  const q = query.trim().toLowerCase();
  if (!q) return portals;
  return portals.filter((p) => {
    const haystack = [
      p.titleFlat,
      p.badge,
      p.description,
      ...p.keywords,
      ...p.searchTerms,
    ]
      .join(' ')
      .toLowerCase();
    return haystack.includes(q);
  });
}

// Cross-portal Deep Search. Returns matching portal cards AND matching
// section entries from the curated content index.
export function searchEverything(query) {
  return {
    portals: searchPortals(query),
    sections: query.trim() ? searchSections(query) : [],
  };
}
